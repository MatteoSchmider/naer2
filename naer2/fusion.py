"""
Fused rounds: one kernel launch for a round in which every population runs, instead of one per population --
the round's programs in one grid, each population's share running its own generated body (fused_template.py:
fused_run, exactly the code its own kernel runs), dispatched on the program id. The default, per network:

    net = pop.network
    net.fuse_rounds = False     # (on by default: a kernel per population instead; changing it drops the
                                #  captured graphs)

Only the launch is shared. Every run stays its population's: its schedule entry, its status, its journal
entry -- a stopped run is rerun through its population's own kernel (runtime._Launches.recover), as without
fusion. Rounds in which only some populations run launch per population as before.

What one kernel for all populations costs: its registers and shared memory are the most any population's body
needs, its compile time grows with the populations, and all of them must use the same warps (one launch, one
block size). Worth it where the populations are alike and all run every round (PD14: ~3 us a round on the
4090, the 9 launches' and their barrier's share -- tools/graph_overhead.py).

    FusedRound(runtimes)            the fused kernel of these runtimes (in this order), generated and loaded
    .covers(runtimes)               whether a round's runs are exactly these runtimes'
    .launch(params, stream)         one launch: params[i] runtime i's run (PopulationRuntime launch params)
"""

import importlib.util

import torch

from .runtime import _direct_launch
from .transpiler.templates.fused_template import CONSTEXPRS, DO_NOT_SPECIALIZE, FIXED_ARGS, module_path


class FusedRound:
    """One fused kernel over the given runtimes' populations: program pid < n_0 runs population 0's group
    pid, the next n_1 population 1's, and so on (their group counts fixed once connected)."""

    def __init__(self, runtimes: list):
        if not runtimes:
            raise ValueError("FusedRound: no runtimes")
        self.runtimes = list(runtimes)
        warps = {rt._warps(None) for rt in self.runtimes}
        if len(warps) > 1:
            raise ValueError(f"FusedRound: the populations' warps differ ({sorted(warps)}): one launch, one "
                             f"block size -- set every runtime's max_warps alike")
        self.num_warps = warps.pop()
        options = {(rt.waves_per_eu, rt.maxnreg) for rt in self.runtimes}
        if len(options) > 1:
            raise ValueError("FusedRound: the populations' compile options (waves_per_eu, maxnreg) differ")
        self.waves_per_eu, self.maxnreg = options.pop()
        bodies = []
        for rt in self.runtimes:
            body = getattr(rt.kernel.kernel, "fn", None)
            body = body.__globals__.get("fused_run") if body is not None else None
            if body is None or list(rt._constexpr_names) != list(CONSTEXPRS):
                raise ValueError("FusedRound: only template-generated kernels fuse (fused_template.py: fused_run)")
            bodies.append(body)
        self.key = tuple((id(rt), id(rt.kernel)) for rt in self.runtimes)
        self.n_programs = sum(rt.n_groups for rt in self.runtimes)
        self.kernel = self._load(self._source(), bodies)
        self._launchers: dict = {}
        self.launches = 0  # (fused launches made: tests, tools)

    def _source(self) -> str:
        args, consts, calls = [], [], []
        off = 0
        for i, rt in enumerate(self.runtimes):
            own = [f"{a}_ptr" for a in rt.kernel.attrs] + list(FIXED_ARGS)
            args += [f"p{i}_{a}" for a in own]
            consts += [f"p{i}_{c}: gl.constexpr" for c in CONSTEXPRS]
            names = ", ".join([f"p{i}_{a}" for a in own] + [f"p{i}_{c}" for c in CONSTEXPRS])
            n = rt.n_groups
            cond = "if" if i == 0 else "elif"
            calls.append(f"    {cond} pid < {off + n}:\n        _run{i}(pid - {off}, {n}, {names})\n")
            off += n
        no_spec = [f"p{i}_{a}" for i in range(len(self.runtimes)) for a in DO_NOT_SPECIALIZE]
        signature = ",\n    ".join(args + consts)
        return f'''"""Generated by naer2/fusion.py -- do not edit."""
from triton.experimental import gluon
from triton.experimental.gluon import language as gl


@gluon.jit(do_not_specialize={no_spec!r})
def fused_round(
    {signature},
):
    pid = gl.program_id(0)
{"".join(calls)}'''

    def _load(self, source: str, bodies: list):
        """The generated module, written to a file (the JIT reads kernel source from one), each population's
        body bound as _run<i> before the first compile."""
        name = f"naer2_fused_round_{id(self)}"
        path = module_path(name)
        path.write_text(source)
        spec = importlib.util.spec_from_file_location(name, path)
        module = importlib.util.module_from_spec(spec)
        for i, body in enumerate(bodies):
            setattr(module, f"_run{i}", body)
        spec.loader.exec_module(module)
        self.source = source
        return module.fused_round

    def covers(self, runtimes) -> bool:
        return len(runtimes) == len(self.runtimes) and {id(rt) for rt in runtimes} == {k for k, _ in self.key}

    def _args(self, params: list) -> tuple[list, tuple, bool]:
        """The fused kernel's arguments for one round (params[i]: runtime i's run), its constexprs' values
        (the compiled variant's key), and whether every state tensor is aligned (the specialization)."""
        args, consts, aligned = [], [], True
        for rt, p in zip(self.runtimes, params):
            a, num_warps, al = rt._launch_args(p)
            if num_warps != self.num_warps:
                raise ValueError("FusedRound.launch: a run's warps differ from the fused kernel's")
            args += a
            aligned &= al
            c = rt._constexprs(num_warps)
            consts += [c[n] for n in CONSTEXPRS]
        return args, tuple(consts), aligned

    def ensure_compiled(self, params: list):
        """The compiled variant for this round's runs, compiled now if it isn't yet -- without launching
        anything (Triton's warmup): before a graph capture, not inside it (a compile under capture allocates,
        and a garbage collection then may free CUDA objects mid-capture). Returns its launcher."""
        args, key, aligned = self._args(params)
        launch = self._launchers.get(key)
        if launch is not None:
            return launch
        kw = {f"p{i}_{c}": key[i * len(CONSTEXPRS) + j]
              for i in range(len(self.runtimes)) for j, c in enumerate(CONSTEXPRS)}
        opts = {"waves_per_eu": self.waves_per_eu} if torch.version.hip else (
            {"maxnreg": self.maxnreg} if self.maxnreg else {})
        compiled = self.kernel.warmup(*args, **kw, num_warps=self.num_warps, grid=(self.n_programs,), **opts)
        self.compiled = compiled  # (the last compiled variant: its registers, shared memory -- tools)
        launch = _direct_launch(compiled, self.n_programs, key)
        if aligned:  # (its specialization: what every aligned call meets)
            self._launchers[key] = launch
        return launch

    def launch(self, params: list, stream=None) -> None:
        """One launch of the round: params[i] runtime i's run, as PopulationRuntime._launch takes it."""
        self.launches += 1
        args, _, _ = self._args(params)
        self.ensure_compiled(params)(args, stream.cuda_stream if stream is not None else None)
